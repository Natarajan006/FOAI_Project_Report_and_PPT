"""PDF assessment report generator using ReportLab."""

from io import BytesIO
from typing import Any

from reportlab.lib import colors
from reportlab.lib.enums import TA_CENTER, TA_LEFT
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import inch
from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle


def generate_assessment_pdf(
    application: dict[str, Any], assessment: dict[str, Any]
) -> bytes:
    """
    Generate a PDF report for a loan eligibility assessment.
    Does NOT include passwords or authentication secrets.
    """
    buffer = BytesIO()
    doc = SimpleDocTemplate(buffer, pagesize=A4, topMargin=0.6 * inch, bottomMargin=0.6 * inch)
    styles = getSampleStyleSheet()
    title_style = ParagraphStyle(
        "TitleCustom",
        parent=styles["Heading1"],
        alignment=TA_CENTER,
        textColor=colors.HexColor("#0a2540"),
        spaceAfter=12,
    )
    heading = ParagraphStyle(
        "HeadingCustom",
        parent=styles["Heading2"],
        textColor=colors.HexColor("#1a56db"),
        spaceBefore=12,
        spaceAfter=6,
    )
    body = ParagraphStyle("BodyCustom", parent=styles["Normal"], fontSize=10, leading=14)
    small = ParagraphStyle("Small", parent=styles["Normal"], fontSize=8, textColor=colors.grey)

    story = []
    story.append(Paragraph("AI-Based Loan Eligibility Assessment Report", title_style))
    story.append(
        Paragraph(
            "Demo report generated by Forward Chaining + Agentic AI system",
            ParagraphStyle("Sub", parent=body, alignment=TA_CENTER, textColor=colors.grey),
        )
    )
    story.append(Spacer(1, 12))

    # Meta
    story.append(Paragraph("Report Information", heading))
    meta_data = [
        ["Application ID", application.get("id", "N/A")],
        ["Assessment ID", assessment.get("id", "N/A")],
        ["Date", str(assessment.get("timestamp", "N/A"))],
        ["Decision", assessment.get("decision", "N/A")],
        ["Risk Level", assessment.get("risk_level", "N/A")],
    ]
    story.append(_table(meta_data))

    # Applicant
    story.append(Paragraph("Applicant Information", heading))
    applicant_data = [
        ["Full Name", application.get("full_name", "")],
        ["Age", str(application.get("age", ""))],
        ["Employment Type", application.get("employment_type", "")],
        ["Employment Duration (months)", str(application.get("employment_duration", ""))],
        ["Repayment History", application.get("repayment_history", "")],
    ]
    story.append(_table(applicant_data))

    # Loan
    story.append(Paragraph("Loan Information", heading))
    loan_data = [
        ["Loan Type", application.get("loan_type", "")],
        ["Requested Amount", f"₹{application.get('requested_amount', 0):,.2f}"],
        ["Tenure (months)", str(application.get("tenure_months", ""))],
        ["Interest Rate (%)", str(application.get("interest_rate", ""))],
        ["Purpose", application.get("purpose", "")],
    ]
    story.append(_table(loan_data))

    # Financial
    fs = assessment.get("financial_summary") or {}
    story.append(Paragraph("Financial Summary", heading))
    fin_data = [
        ["Monthly Income", f"₹{fs.get('monthly_income', application.get('monthly_income', 0)):,.2f}"],
        ["Monthly Expenses", f"₹{fs.get('monthly_expenses', application.get('monthly_expenses', 0)):,.2f}"],
        ["Existing EMI", f"₹{fs.get('existing_emi', application.get('existing_emi', 0)):,.2f}"],
        ["Estimated New EMI", f"₹{fs.get('estimated_new_emi', 0):,.2f}"],
        ["Demo Credit Score", str(fs.get("credit_score", application.get("credit_score", "")))],
        ["Debt-to-Income (DTI) %", str(fs.get("debt_to_income_ratio", "N/A"))],
    ]
    story.append(_table(fin_data))

    # Decision & explanation
    story.append(Paragraph("Eligibility Result & AI Explanation", heading))
    story.append(Paragraph(f"<b>Decision:</b> {assessment.get('decision', 'N/A')}", body))
    story.append(Paragraph(f"<b>Risk Level:</b> {assessment.get('risk_level', 'N/A')}", body))
    story.append(Spacer(1, 6))
    story.append(Paragraph(assessment.get("explanation", "No explanation available."), body))

    # Rules
    story.append(Paragraph("Rules Triggered", heading))
    rules = assessment.get("triggered_rules") or []
    if rules:
        rule_rows = [["Rule ID", "Name", "Conclusion"]]
        for r in rules:
            rule_rows.append([r.get("rule_id", ""), r.get("name", ""), r.get("conclusion", "")])
        t = Table(rule_rows, colWidths=[1 * inch, 2.5 * inch, 2.5 * inch])
        t.setStyle(
            TableStyle(
                [
                    ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#0a2540")),
                    ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
                    ("FONTSIZE", (0, 0), (-1, -1), 8),
                    ("GRID", (0, 0), (-1, -1), 0.5, colors.grey),
                    ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#f0f4f8")]),
                    ("VALIGN", (0, 0), (-1, -1), "TOP"),
                ]
            )
        )
        story.append(t)
    else:
        story.append(Paragraph("No rules triggered.", body))

    # Risk factors
    story.append(Paragraph("Risk Factors", heading))
    for f in assessment.get("risk_factors") or ["None"]:
        story.append(Paragraph(f"• {f}", body))

    # Disclaimer
    story.append(Spacer(1, 20))
    story.append(
        Paragraph(
            "DISCLAIMER: This report is generated by a college demo system using sample "
            "Forward Chaining rules. It is NOT real bank underwriting, NOT a credit bureau "
            "report, and NOT financial advice. Demo thresholds only.",
            small,
        )
    )

    doc.build(story)
    return buffer.getvalue()


def _table(data: list[list[str]]) -> Table:
    t = Table(data, colWidths=[2.2 * inch, 4 * inch])
    t.setStyle(
        TableStyle(
            [
                ("FONTNAME", (0, 0), (0, -1), "Helvetica-Bold"),
                ("FONTSIZE", (0, 0), (-1, -1), 9),
                ("TEXTCOLOR", (0, 0), (0, -1), colors.HexColor("#0a2540")),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
                ("TOPPADDING", (0, 0), (-1, -1), 4),
                ("VALIGN", (0, 0), (-1, -1), "TOP"),
            ]
        )
    )
    return t
